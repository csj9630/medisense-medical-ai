"""LLM 호출 전에 먼저 도는 응급 키워드 하드 필터.

⚠️ 중요: 이건 "의료 트리아지 규칙"이 아니라 소프트웨어 엔지니어링 관점의 안전장치다.
아래 키워드 목록은 의료진 자문 없이 만든 예시 뼈대이므로, 운영 반영 전 반드시
의료 자문을 받아 검증할 것.

왜 필요한가: 시스템 프롬프트(prompts/system_prompt.md)의 "# 9. 응급 상황"이 이미
LLM에게 "응급이면 우선 대응하라"고 지시하지만, 이건 LLM이 지시를 실제로 따를
것이라는 가정에 전적으로 의존한다. 여기서는 그 가정과 무관하게, 특정 키워드가
있으면 **LLM을 아예 호출하지 않고** 고정된 안전 응답으로 강제 전환한다 — LLM의
프롬프트 준수 실패(hallucination, 지시 무시)에 대비한 이중 안전장치.
"""

import re

_HIGH_RISK_KEYWORDS = (
    "숨쉬기 힘들", "숨차", "호흡곤란", "숨이 안 쉬어", "숨을 못 쉬",
    "가슴 통증", "가슴이 아파", "흉통", "가슴 쥐어짜", "가슴 조이", "가슴 답답",
    "의식", "쓰러", "실신",
    "심한 출혈", "피를 토", "각혈",
    "경련", "발작",
    "마비", "말이 어눌",
)
# "숨이 안 쉬어"/"숨을 못 쉬"(호흡곤란)와 "가슴 쥐어짜"/"가슴 조이"(흉통)는 2026-09
# 실측(scripts/eval_risk_detector.py)에서 놓친 실제 환자 표현을 같은 카테고리 안에서
# 보강한 것 — 새 응급 범주를 추가한 게 아니라 기존 두 범주의 표현 다양성만 넓혔다.
# "가슴 답답"도 같은 실측에서 추가— "가슴이 답답하고 통증이 있어요"가 "가슴"과
# "통증" 사이 글자 수(7자)가 기존 gap 허용치(6자)를 넘어서 "가슴 통증" 키워드로는
# 못 잡히던 걸, "가슴"+"답답"(사이 2자) 조합으로 보강해 잡는다.

# 여러 단어로 된 키워드는 실제 문장에서 조사/어미가 그 사이에 자연스럽게 끼어든다
# (예: "숨쉬기 힘들" 키워드가 "숨쉬기가 너무 힘들어요"는 못 잡음 — 2026-09 실측으로
# 확인된 재현율 손실의 절반가량이 이 문제였다). 공백을 "최대 N자 이내 아무 문자"로
# 바꿔 그 정도 삽입은 허용하되, 문장 전체에서 무관한 단어끼리 엮이지 않게 폭은 좁게
# 유지한다. 공백이 없는 단일 키워드는 기존과 동일하게 정확한 부분 문자열 매칭이다.
#
# 갭을 6자로 뒀을 때도 재발했다 — "가슴 쥐어짜"가 "가슴 한가운데가 쥐어짜듯이"(갭 7자,
# "한가운데가"+공백 2개)를 놓쳐서 심근경색 의심 증상이 응급 필터를 통과 못 하고 LLM
# 자유생성으로 넘어간 사례가 실측으로 확인됐다(2026-09). "한가운데", "쪽 부위가" 같은
# 부위 수식어까지 감안해 15자로 넓혔다 — 이 정도는 같은 문장 안에서만 걸리므로 무관한
# 키워드끼리 엮일 위험은 여전히 낮다.
_KEYWORD_GAP = 15
_PATTERNS = [
    re.compile(f".{{0,{_KEYWORD_GAP}}}".join(re.escape(part) for part in keyword.split(" ")))
    for keyword in _HIGH_RISK_KEYWORDS
]

EMERGENCY_RESPONSE = (
    "⚠️ 말씀하신 증상은 응급 상황일 가능성을 고려해야 합니다. "
    "증상이 현재 심하게 나타나고 있다면 지체하지 말고 119에 신고하거나 "
    "가까운 응급실을 방문해 주세요."
)


def detect_emergency(text: str) -> bool:
    return any(pattern.search(text) for pattern in _PATTERNS)
