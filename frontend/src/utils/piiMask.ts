/**
 * OCR로 추출한 텍스트를 미리보기에 보여주기 전에, 주민등록번호/전화번호/주소처럼
 * 흔한 개인정보를 마스킹한다. 업로드한 문서(처방전, 검사결과지, 신분증 등)에 이런
 * 정보가 그대로 찍혀 나오는 경우가 실제로 있어서, 화면에 노출되기 전에 가린다.
 *
 * 정규식 기반 최선의 노력(best-effort)이다 — 특히 주소는 형식이 일정하지 않아서
 * 완벽하게 잡아내지 못할 수 있다. DocumentPreviewPanel의 "추출된 텍스트" 칸이
 * 수정 가능(textarea)하므로, 놓친 항목은 사용자가 직접 지우거나 고칠 수 있다 —
 * 이 함수는 완전 자동화가 아니라 기본값을 안전한 쪽으로 두는 안전장치다.
 */

// 주민등록번호/외국인등록번호: 000000-0000000 (뒤 7자리 첫 숫자가 보통 1~8이지만,
// 오탐보다 누락이 더 위험하므로 굳이 값 범위를 제한하지 않고 자릿수만 본다).
const RESIDENT_NUMBER = /\d{6}\s?-\s?\d{7}/g;

// 휴대폰/일반 전화번호: 010-1234-5678, 02-123-4567, 031-1234-5678 등.
// 0으로 시작하는 지역/이동통신 국번 뒤에 3~4자리-4자리가 오는 흔한 형태만 잡는다.
const PHONE_NUMBER = /0\d{1,2}[\s.-]?\d{3,4}[\s.-]?\d{4}/g;

// 주소: "OO시/도 (OO시/군/구 최대 2단계) OO동/로/길 (번지/호)"류의 흔한 한국 주소
// 패턴만 잡는다 - 완전한 주소 파서가 아니라 시작 지점(시/도)부터 번지/호 근처까지를
// 느슨하게 묶어서 가린다. "서울특별시 강남구 테헤란로 123",
// "경기도 성남시 분당구 판교역로 235" 둘 다 커버하도록 중간 행정구역을 0~2개 허용한다.
const ADDRESS =
  /[가-힣]{2,}(?:특별시|광역시|특별자치시|특별자치도|도)(?:\s?[가-힣]{1,}(?:시|군|구)){0,2}\s?[가-힣0-9]{1,}(?:읍|면|동|로|길)\s?[0-9-]{0,10}(?:번지|호)?/g;

function maskMatch(match: string): string {
  return '*'.repeat(Math.min(match.trim().length, 12));
}

export function maskPII(text: string): string {
  if (!text) return text;
  // 순서 중요: 주민등록번호를 먼저 마스킹해야 그 안의 숫자가 전화번호 패턴으로
  // 다시 걸려서 이중으로(또는 어긋나게) 처리되는 걸 막는다.
  return text
    .replace(RESIDENT_NUMBER, maskMatch)
    .replace(PHONE_NUMBER, maskMatch)
    .replace(ADDRESS, maskMatch);
}
